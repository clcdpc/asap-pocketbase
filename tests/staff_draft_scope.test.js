const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

(async () => {
  const source = fs.readFileSync(path.join(__dirname, '../src/Asap.Web/Frontend/staff/js/draft-scope.js'), 'utf8');
  const { createDraftScope } = await import(`data:text/javascript;base64,${Buffer.from(source).toString('base64')}`);
  const scope = createDraftScope();
  const root = { isConnected: true };
  let value = 'baseline';
  const own = scope.register({ root, isDirty: () => value !== 'baseline' });
  assert.equal(scope.owns(own), true);
  const siblingRoot = { isConnected: true };
  let siblingDirty = false;
  const metadata = { label: 'Staff-account edits', section: 'Staff access' };
  const sibling = scope.register({ root: siblingRoot, isDirty: () => siblingDirty, kind: 'staff editor', metadata });
  assert.equal(scope.admit().allowed, false);
  assert.equal(scope.admit({}).reason, 'missing_consumption');
  assert.equal(scope.admit({ consumes: undefined }).allowed, false);
  value = 'draft';
  assert.equal(scope.isDirty(), true);
  assert.equal(scope.admit({ consumes: null }).allowed, false);
  assert.equal(scope.admit({ consumes: own }).allowed, true);
  assert.equal(scope.isDirty(), true, 'consumption grants permission without clearing at dispatch');
  siblingDirty = true;
  assert.equal(scope.admit({ consumes: own }).reason, 'competing_draft');
  assert.equal(scope.admit({ consumes: own, preserves: [sibling] }).allowed, true);
  assert.equal(scope.isDirty(), true, 'preserving a sibling grants admission without accepting either draft');
  assert.equal(scope.admit({ consumes: null, preserves: [own, sibling] }).reason, 'invalid_preservation');
  assert.equal(scope.admit({ consumes: own, preserves: 'all' }).reason, 'invalid_preservation');
  const third = scope.register({ root, isDirty: () => true });
  const blocked = scope.admit({ consumes: own });
  assert.equal(blocked.kind, 'staff editor', 'Existing first-kind consumers retain their admission detail.');
  assert.deepEqual(blocked.blockers, [{ handle: sibling, kind: 'staff editor', metadata }, { handle: third, kind: 'inline', metadata: null }]);
  assert.deepEqual(scope.admit({ consumes: own, preserves: [sibling] }).blockers.map(item => item.handle), [third],
    'Only actual unconsumed/unpreserved dirty owners are enumerated.');
  assert.equal(scope.admit({ consumes: own, preserves: [sibling] }).reason, 'competing_draft',
    'an explicit preservation list never permits an undeclared dirty owner');
  scope.release(third);
  value = 'baseline';
  assert.equal(scope.admit({ consumes: sibling }).allowed, true);
  const foreign = createDraftScope().register({ root, isDirty: () => true });
  assert.equal(scope.admit({ consumes: foreign }).reason, 'invalid_owner');
  assert.equal(scope.admit({ consumes: own, preserves: [foreign] }).reason, 'invalid_preservation');
  siblingRoot.isConnected = false;
  assert.equal(scope.isDirty(), false);
  assert.equal(scope.admit({ consumes: sibling }).allowed, false);
  assert.equal(scope.admit({ consumes: own, preserves: [sibling] }).reason, 'invalid_preservation',
    'a detached preserved owner cannot authorize a command');
  siblingRoot.isConnected = true;
  assert.equal(scope.owns(sibling), false);
  assert.equal(scope.admit({ consumes: sibling }).reason, 'invalid_owner', 'Reinsertion never restores a pruned handle.');
  scope.release(own);
  assert.equal(scope.admit({ consumes: own }).allowed, false);
  scope.dispose();
  assert.equal(scope.admit({ consumes: null }).allowed, false);
  assert.throws(() => scope.register({ root, isDirty: () => false }));
  const replacement = createDraftScope();
  assert.equal(replacement.admit({ consumes: own }).allowed, false);
  assert.equal(replacement.owns(own), false);
  assert.equal(replacement.admit({ consumes: null }).allowed, true);
  const { JSDOM } = require('jsdom');
  const dom = new JSDOM('<main><article></article><article></article></main>');
  const mounted = createDraftScope(), document = dom.window.document, article = document.querySelector('article');
  const mountedOwner = mounted.register({ root: article, isDirty: () => true });
  document.querySelector('main').append(article);
  await new Promise(resolve => setImmediate(resolve));
  assert.equal(mounted.admit({ consumes: mountedOwner }).allowed, true, 'Synchronous mounted reorders retain their owner.');
  article.remove();
  await new Promise(resolve => setImmediate(resolve));
  document.querySelector('main').append(article);
  assert.equal(mounted.admit({ consumes: mountedOwner }).reason, 'invalid_owner', 'A disconnected turn retires the owner before reinsertion.');
  mounted.dispose(); dom.window.close();
  console.log('Local draft scope ownership, admission and disposal contracts passed');
})().catch(error => { console.error(error); process.exitCode = 1; });
